#!/usr/bin/env python3
"""Writes dashboard/public/icons.js from the lucide-static npm package (ISC licence).
Usage: make_web_icons.py <dir containing lucide/package> <dashboard/public>"""
import re, sys
src, out = sys.argv[1], sys.argv[2]
NAMES = """layout-grid message-circle plug settings plus search x check smartphone sparkles keyboard send trash-2 pencil
video notebook-text calendar globe sun key-round languages circle-dashed arrow-right log-out cloud-sun""".split()
items = []
for name in NAMES:
    svg = open(f"{src}/lucide/package/icons/{name}.svg").read()
    inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
    items.append(f"  {name.replace('-', '_')}: '{' '.join(inner.split())}',")
open(f"{out}/icons.js", "w").write("// Generated by tools/make_web_icons.py from lucide (ISC licence). Inner SVG markup per icon.\nwindow.ICONS = {\n" + "\n".join(items) + "\n};\n")
print(len(NAMES), "web icons")
